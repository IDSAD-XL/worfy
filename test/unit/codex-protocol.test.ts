// The generated Codex protocol (worfy-multi-vendor ticket 17): `scripts/codex-protocol.mjs --check`,
// part of pnpm lint, fails when protocol/VERSION is not the version package.json pins; the JSON Schema
// bundle of that version compiles in the strict ajv of src/main/vendors/codex/schema.ts and checks a
// message. The check never runs Codex.
import { spawnSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import { CODEX_SCHEMA_BUNDLE, codexAjv } from '../../src/main/vendors/codex/schema'
import { removeTestTree } from '../remove'
import { scriptNode } from '../script-node'

const REPO = join(import.meta.dirname, '..', '..')
const SCRIPT = join(REPO, 'scripts', 'codex-protocol.mjs')
const PROTOCOL = join('src', 'main', 'vendors', 'codex', 'protocol')

const roots: string[] = []
afterEach(() => {
  for (const root of roots.splice(0)) removeTestTree(root)
})

/** Runs the check on the repository `root`, under the real node (test/script-node.ts). */
function check(root: string): { status: number | null; stdout: string; stderr: string } {
  const child = spawnSync(scriptNode(), [SCRIPT, '--check', '--root', root], { encoding: 'utf8' })
  return { status: child.status, stdout: child.stdout, stderr: child.stderr }
}

/** A repository with package.json pinning `pinned`, and protocol/VERSION `generated` (none when null) with both outputs. */
function repository(pinned: string, generated: string | null, outputs: readonly string[] = ['ts', 'json']): string {
  const root = mkdtempSync(join(tmpdir(), 'worfy-codex-protocol-'))
  roots.push(root)
  writeFileSync(join(root, 'package.json'), JSON.stringify({ dependencies: { '@openai/codex': pinned } }))
  mkdirSync(join(root, PROTOCOL), { recursive: true })
  if (generated !== null) writeFileSync(join(root, PROTOCOL, 'VERSION'), `${generated}\n`)
  for (const dir of outputs) {
    mkdirSync(join(root, PROTOCOL, dir))
    writeFileSync(join(root, PROTOCOL, dir, 'x'), '')
  }
  return root
}

describe('codex-protocol --check', () => {
  it('passes this repository: the protocol was generated by the Codex package.json pins', () => {
    const pinned = (JSON.parse(readFileSync(join(REPO, 'package.json'), 'utf8')) as { dependencies: Record<string, string> }).dependencies['@openai/codex']
    const { status, stdout, stderr } = check(REPO)
    expect(stderr).toBe('')
    expect(status).toBe(0)
    expect(stdout).toBe(`codex-protocol: ok (${pinned})\n`)
  })

  it('passes a VERSION that matches, CRLF or not', () => {
    const root = repository('0.166.0', '0.166.0')
    writeFileSync(join(root, PROTOCOL, 'VERSION'), '0.166.0\r\n')
    expect(check(root).status).toBe(0)
  })

  it('fails a VERSION that is not the pinned version, and says what to run', () => {
    const { status, stderr } = check(repository('0.167.0', '0.166.0'))
    expect(status).toBe(1)
    expect(stderr).toContain('VERSION: generated by Codex 0.166.0, package.json pins 0.167.0; run node scripts/codex-protocol.mjs')
  })

  it('fails a protocol without VERSION, and one without the TypeScript types', () => {
    expect(check(repository('0.166.0', null)).stderr).toMatch(/VERSION: missing/)
    const noTypes = check(repository('0.166.0', '0.166.0', ['json']))
    expect(noTypes.status).toBe(1)
    expect(noTypes.stderr).toMatch(/protocol\/ts: missing or empty/)
  })

  it('stops with 2 when package.json pins no exact version of Codex', () => {
    const { status, stderr } = check(repository('^0.166.0', '0.166.0'))
    expect(status).toBe(2)
    expect(stderr).toMatch(/exact version/)
  })
})

describe('the JSON Schema bundle of the pinned Codex', () => {
  const bundle = JSON.parse(readFileSync(join(REPO, PROTOCOL, 'json', CODEX_SCHEMA_BUNDLE), 'utf8')) as { definitions: Record<string, unknown> & { v2: Record<string, unknown> } }

  it('compiles in strict ajv, every definition of v1 and v2', () => {
    const ajv = codexAjv()
    ajv.addSchema(bundle, 'codex')
    const names = [...Object.keys(bundle.definitions).filter((name) => name !== 'v2'), ...Object.keys(bundle.definitions.v2).map((name) => `v2/${name}`)]
    expect(names.length).toBeGreaterThan(100)
    for (const name of names) expect(ajv.getSchema(`codex#/definitions/${name}`), name).toBeTypeOf('function')
  })

  it('takes a well-formed initialize request and refuses one without clientInfo', () => {
    const ajv = codexAjv()
    ajv.addSchema(bundle, 'codex')
    const request = ajv.getSchema('codex#/definitions/ClientRequest')
    if (request === undefined) throw new Error('no ClientRequest in the bundle')
    expect(request({ id: 1, method: 'initialize', params: { clientInfo: { name: 'worfy', version: '0.3.0' } } })).toBe(true)
    expect(request({ id: 1, method: 'initialize', params: {} })).toBe(false)
  })

  it('checks the number formats of the Rust types: sign and range', () => {
    const ajv = codexAjv()
    const uint32 = ajv.compile({ type: 'integer', format: 'uint32' })
    expect([0, 2 ** 32 - 1, -1, 2 ** 32].map((value) => uint32(value))).toEqual([true, true, false, false])
    const int32 = ajv.compile({ type: 'integer', format: 'int32' })
    expect([-(2 ** 31), 2 ** 31].map((value) => int32(value))).toEqual([true, false])
    const uint64 = ajv.compile({ type: 'integer', format: 'uint64' })
    expect([2 ** 60, -1].map((value) => uint64(value))).toEqual([true, false])
    const double = ajv.compile({ type: 'number', format: 'double' })
    expect(double(0.5)).toBe(true)
  })
})
